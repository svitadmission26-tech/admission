// The SVIT ERP module registry.
//
// Every module of the ERP is described here once. The generic module screen
// (src/components/ErpModuleScreen.jsx) renders the dashboard, the record
// list, the filters, the form, the Excel tools and the PDF output from this
// configuration, so a new module is a configuration change and a migration
// instead of a new React file.
//
// Field types
//   text | textarea | number | money | date | time | datetime
//   select | radio | boolean | email | phone | url | reference | json
//
// A reference field points at another master table:
//   { key: 'course_id', label: 'Course', type: 'reference', ref: 'courses',
//     refLabel: 'course', matchColumns: ['name', 'code'] }

// Amounts are stored in paise (integers) everywhere in the ERP.
export const money = (paise) =>
	`₹${(Number(paise || 0) / 100).toLocaleString('en-IN', {
		minimumFractionDigits: 2,
		maximumFractionDigits: 2,
	})}`;

export const moneyValue = (paise) => Number(paise || 0) / 100;

// Helpers that keep the table configuration short.
const reference = (key, label, ref, matchColumns = ['name'], refLabel = ref) => ({
	key,
	label,
	type: 'reference',
	ref,
	refLabel,
	matchColumns,
});

const text = (key, label, extra = {}) => ({ key, label, type: 'text', ...extra });
const number = (key, label, extra = {}) => ({ key, label, type: 'number', ...extra });
const amount = (key, label, extra = {}) => ({ key, label, type: 'money', ...extra });
const date = (key, label, extra = {}) => ({ key, label, type: 'date', ...extra });
const select = (key, label, options, extra = {}) => ({
	key,
	label,
	type: 'select',
	options,
	...extra,
});
const flag = (key, label, extra = {}) => ({ key, label, type: 'boolean', ...extra });

