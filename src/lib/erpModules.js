// The record list that holds the main data of a module.
//
// The primary list is the one that opens when the module is opened, so the
// students module opens on the students, the faculty module on the faculty,
// the accounts module on the ledger and the transport module on the routes.
export function erpModulePrimaryTable(module) {
	if (!module) return null;
	const tables = module.tables ?? [];
	return tables.find((table) => table.key === module.primary) ?? tables[0] ?? null;
}

// The pages of every module, used to build the navigation.
export function erpModulePages(module) {
	const pages = new Set([module.entryPage]);
	for (const table of module.tables ?? []) {
		pages.add(table.title);
	}
	return Array.from(pages);
}

// Every table configuration of the ERP, flattened.
export function erpAllTables() {
	return erpModules.flatMap((module) =>
		(module.tables ?? []).map((table) => ({
			...table,
			moduleId: module.id,
			moduleTitle: module.title,
		})),
	);
}

// Find a table configuration by its key.
export function erpTableConfig(key) {
	return erpAllTables().find((table) => table.key === key) ?? null;
}
