const XLSX_MIME =
	'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

function safeSheetName(name) {
	return name.replace(/[\\/?*:[\]]/g, ' ').slice(0, 31) || 'Data';
}

function safeCellValue(value) {
	if (value === null || value === undefined) return '';
	if (typeof value === 'object') return JSON.stringify(value);
	if (typeof value === 'string' && /^[=+\-@\t\r]/.test(value)) return `'${value}`;
	return value;
}

function formatWorksheet(worksheet, columns) {
	worksheet.columns = columns.map((column) => ({
		header: column.label || column.key,
		key: column.key,
		width: Math.min(Math.max((column.label || column.key).length + 4, 14), 36),
	}));
	worksheet.views = [{ state: 'frozen', ySplit: 1 }];
	worksheet.autoFilter = {
		from: { row: 1, column: 1 },
		to: { row: 1, column: columns.length },
	};
	worksheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
	worksheet.getRow(1).fill = {
		type: 'pattern',
		pattern: 'solid',
		fgColor: { argb: 'FF1459B5' },
	};
}

async function loadExcelJs() {
	const module = await import('exceljs');
	return module.default || module;
}

async function saveWorkbook(workbook, fileName) {
	const buffer = await workbook.xlsx.writeBuffer();
	const url = URL.createObjectURL(
		new Blob([buffer], { type: XLSX_MIME }),
	);
	const link = document.createElement('a');
	link.href = url;
	link.download = fileName.endsWith('.xlsx') ? fileName : `${fileName}.xlsx`;
	link.click();
	setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function downloadExcel({ fileName, sheetName, columns, rows }) {
	const ExcelJS = await loadExcelJs();
	const workbook = new ExcelJS.Workbook();
	workbook.creator = 'SVIT Admission ERP';
	workbook.created = new Date();
	const worksheet = workbook.addWorksheet(safeSheetName(sheetName));
	formatWorksheet(worksheet, columns);
	for (const row of rows) {
		const values = Object.fromEntries(
			columns.map(({ key }) => [key, safeCellValue(row[key])]),
		);
		worksheet.addRow(values);
	}
	await saveWorkbook(workbook, fileName);
}

export async function downloadExcelTemplate({
	fileName,
	sheetName,
	columns,
	instructions = [],
}) {
	const ExcelJS = await loadExcelJs();
	const workbook = new ExcelJS.Workbook();
	workbook.creator = 'SVIT Admission ERP';
	const worksheet = workbook.addWorksheet(safeSheetName(sheetName));
	formatWorksheet(worksheet, columns);
	worksheet.addRow(Object.fromEntries(columns.map(({ key }) => [key, ''])));
	const help = workbook.addWorksheet('Instructions');
	help.addRows([
		['SVIT Admission ERP - Excel Template'],
		['Use the first worksheet for data. Do not rename or reorder its headers.'],
		['Leave a row blank to skip it. IDs and timestamps are generated by the system.'],
		...instructions.map((instruction) => [instruction]),
	]);
	help.getColumn(1).width = 110;
	help.getRow(1).font = { bold: true, size: 14 };
	await saveWorkbook(workbook, fileName);
}

export async function readExcelRows(file, expectedColumns) {
	const ExcelJS = await loadExcelJs();
	const workbook = new ExcelJS.Workbook();
	await workbook.xlsx.load(await file.arrayBuffer());
	const worksheet = workbook.worksheets[0];
	if (!worksheet || worksheet.rowCount < 1) {
		throw new Error('The workbook does not contain a data sheet.');
	}

	const headers = worksheet
		.getRow(1)
		.values.slice(1)
		.map((header) => String(header ?? '').trim());
	const expected = expectedColumns.map(({ label, key }) => label || key);
	if (
		headers.length !== expected.length ||
		headers.some((header, index) => header !== expected[index])
	) {
		throw new Error(
			`Template columns do not match. Download the current ${expectedColumns.length}-column template and keep its headers unchanged.`,
		);
	}

	const rows = [];
	worksheet.eachRow({ includeEmpty: false }, (worksheetRow, rowNumber) => {
		if (rowNumber === 1) return;
		const row = {};
		let hasValue = false;
		expectedColumns.forEach(({ key }, index) => {
			const cell = worksheetRow.getCell(index + 1);
			if (cell.type === ExcelJS.ValueType.Formula || cell.type === ExcelJS.ValueType.Hyperlink) {
				throw new Error(`Formulas and hyperlinks are not allowed (row ${rowNumber}).`);
			}
			let value = cell.value;
			if (value && typeof value === 'object' && 'text' in value) {
				value = value.text;
			}
			if (value instanceof Date) value = value.toISOString().slice(0, 10);
			if (value !== null && value !== undefined && String(value).trim() !== '')
				hasValue = true;
			row[key] = value === null || value === undefined ? '' : value;
		});
		if (hasValue) rows.push(row);
	});
	if (!rows.length) throw new Error('The template contains no data rows.');
	return rows;
}

