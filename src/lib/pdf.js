// PDF / print helpers.
//
// The ERP does not ship a PDF engine. Every document is rendered as a
// print-ready HTML document and handed to the browser print dialog, where the
// user can save it as a PDF. The same renderer produces the receipts, the
// marksheets, the reports and the module listings.

const escapeHtml = (value) =>
	String(value ?? '').replace(/[&<>"']/g, (character) => ({
		'&': '&amp;',
		'<': '&lt;',
		'>': '&gt;',
		'"': '&quot;',
		"'": '&#39;',
	})[character]);

export { escapeHtml };

function openPrintWindow(title) {
	const popup = window.open('', '_blank');
	if (!popup) {
		throw new Error('Allow pop-ups to print the document.');
	}
	popup.document.open();
	popup.document.write(`<!doctype html><html><head><title>${escapeHtml(title)}</title>`);
	return popup;
}

