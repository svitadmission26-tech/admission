// Print a tabular document (a list, a report, a marksheet).
export function printTable({
	title,
	subtitle = '',
	meta = [],
	columns = [],
	rows = [],
	totals = null,
	footer = '',
	college = null,
	autoPrint = true,
}) {
	const popup = openPrintWindow(title);
	const head = columns
		.map(
			(column) =>
				`<th class="${column.align === 'right' ? 'num' : ''}">${escapeHtml(
					column.label ?? column.key,
				)}</th>`,
		)
		.join('');
	const body = rows
		.map(
			(row) =>
				`<tr>${columns
					.map(
						(column) =>
							`<td class="${column.align === 'right' ? 'num' : ''}">${escapeHtml(
								column.value ? column.value(row) : row[column.key],
							)}</td>`,
					)
					.join('')}</tr>`,
		)
		.join('');
	const metaRows = meta
		.map(
			([label, value]) =>
				`<tr><th>${escapeHtml(label)}</th><td>${escapeHtml(value)}</td></tr>`,
		)
		.join('');
	const totalRow = totals
		? `<tfoot><tr>${columns
				.map(
					(column, index) =>
						index === 0
							? `<td>${escapeHtml(totals.label ?? 'Total')}</td>`
							: `<td class="${column.align === 'right' ? 'num' : ''}">${escapeHtml(
									totals.values?.[column.key] ?? '',
								)}</td>`,
				)
				.join('')}</tr></tfoot>`
		: '';
	popup.document.write(`
		<style>${documentStyles}</style>
		<body>
			<header>
				${college?.logo_url ? `<img src="${escapeHtml(college.logo_url)}" alt="College logo">` : ''}
				${college?.name ? `<h2>${escapeHtml(college.name)}</h2>` : ''}
				<h1>${escapeHtml(title)}</h1>
				${subtitle ? `<p class="subtitle">${escapeHtml(subtitle)}</p>` : ''}
			</header>
			${metaRows ? `<table class="meta">${metaRows}</table>` : ''}
			<table>
				<thead><tr>${head}</tr></thead>
				<tbody>${body || '<tr><td colspan="' + columns.length + '">No records</td></tr>'}</tbody>
				${totalRow}
			</table>
			<div class="signature"><div>Prepared by</div><div>Verified by</div><div>Authorised signatory</div></div>
			<footer>${escapeHtml(footer || `Generated by the SVIT College ERP on ${new Date().toLocaleString()}`)}</footer>
			${autoPrint ? '<script>window.addEventListener("load",()=>window.print())</script>' : ''}
		</body></html>`);
	popup.document.close();
	return popup;
}

// Print a receipt that follows a saved receipt template.
export function printReceipt({
	title = 'Receipt',
	college = null,
	reference = '',
	meta = [],
	lines = [],
	totals = [],
	footer = '',
	amountLabel = 'Total',
}) {
	const popup = openPrintWindow(title);
	const metaRows = meta
		.map(
			([label, value]) =>
				`<tr><th>${escapeHtml(label)}</th><td>${escapeHtml(value)}</td></tr>`,
		)
		.join('');
	const lineRows = lines
		.map(
			(line) =>
				`<tr><td>${escapeHtml(line[0])}</td><td class="num">${escapeHtml(
					line[1],
				)}</td></tr>`,
		)
		.join('');
	const totalRows = totals
		.map(
			([label, value]) =>
				`<tr><th>${escapeHtml(label)}</th><td class="num">${escapeHtml(
					value,
				)}</td></tr>`,
		)
		.join('');
	popup.document.write(`
		<style>${documentStyles}</style>
		<body>
			<header>
				${college?.logo_url ? `<img src="${escapeHtml(college.logo_url)}" alt="College logo">` : ''}
				${college?.name ? `<h2>${escapeHtml(college.name)}</h2>` : ''}
				<h1>${escapeHtml(title)}</h1>
				${reference ? `<p class="subtitle">Reference ${escapeHtml(reference)}</p>` : ''}
			</header>
			<table class="meta">${metaRows}</table>
			${lineRows ? `<table><tbody>${lineRows}</tbody></table>` : ''}
			<table class="meta">${totalRows}</table>
			<div class="signature"><div>Received by</div><div>Accountant</div><div>Principal</div></div>
			<footer>${escapeHtml(footer || `Generated by the SVIT College ERP on ${new Date().toLocaleString()}`)}</footer>
			<script>window.addEventListener("load",()=>window.print())</script>
		</body></html>`);
	popup.document.close();
	return popup;
}
